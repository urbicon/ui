/**
 * Resolve an icon by name from the built-in {@link DEFAULT_ICONS} registry,
 * honouring `IconProvider` overrides. This intentionally references the full
 * registry, so importing `getIcon` pulls every icon into the bundle — it is
 * meant for the dynamic, by-name `<Icon name="…" />` component. Components with
 * statically known icons should use `resolveIcon` (from `./icon.context`) instead.
 *
 * Must be called during component initialisation.
 */
export function getIcon(name: IconName): IconComponent {
  const overrides = getIconOverrides();
  return overrides?.[name] ?? DEFAULT_ICONS[name];
}

/** Get metadata for a specific icon. */
export function getIconMeta(name: IconName): IconMeta {
  return ICON_METADATA[name];
}

/** Get all icon names. */
export function getAllIconNames(): IconName[] {
  return Object.keys(DEFAULT_ICONS) as IconName[];
}

/** Get icon names filtered by category. */
export function getIconsByCategory(category: IconCategory): IconName[] {
  return (Object.entries(ICON_METADATA) as [IconName, IconMeta][])
    .filter(([, meta]) => meta.categories.includes(category))
    .map(([name]) => name);
}
